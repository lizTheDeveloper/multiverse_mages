/**
 * `ui/session.json` and `ui/design-dashboard/data.json` are both pure functions
 * of this repository, and both used to be **committed and pinned byte-for-byte**
 * by a test. This builds them instead, and gates the properties that make
 * building them safe.
 *
 *     npm run check:generated
 *
 * ## Why they stopped being committed
 *
 * A committed generated file has to be regenerated by whoever moves its inputs,
 * and the inputs here are the whole repository. Measured cost, all of it
 * observed rather than argued:
 *
 *  - **The pin reddened `main` three times, and each fix narrowed what it
 *    proved.** `fileSeal` was projected out of the equality after #72's baseline
 *    refresh landed mid-build; the reachability totals and line numbers were
 *    projected out after the same thing happened again; the finding rows and
 *    `findingCount` went after #156 fixed a finding and turned `main` red for it.
 *    Three projections in a row is the shape being wrong, not the fields.
 *  - **The third projection blinded the pin completely.** Measured on 63f44ced,
 *    the tip of `main`: the committed payload disagreed with fresh output in
 *    `examinedSymbolCount` (858 vs 864), `productionFileCount` (309 vs 313) and
 *    `NO_DEMAND`'s line number (84 vs 132) — and those are *exactly* the three
 *    fields the last projection carved out. The pin was green over a stale file.
 *    That is the failure mode the pin existed to prevent, arrived at by
 *    successfully defending the pin.
 *  - **`data.json` embeds every gate's provenance,** so a baseline re-record also
 *    required `npm run ui:dashboard` — a coupling that had to be broadcast by
 *    hand and that branches still got wrong.
 *  - **A 1.1 MB JSON conflict is not a conflict anybody resolves.** They
 *    regenerate, which means the merge is decided by whoever ran the command
 *    last.
 *
 * Not committing them deletes all of that. **The "committed payload is stale"
 * failure mode is not preserved here — it is removed by construction**, because
 * there is no committed payload. What has to be gated instead is the two
 * properties that removal depends on.
 *
 * ## The two properties this gates
 *
 * 1. **Each generator is deterministic.** If a payload depended on the clock,
 *    the machine or the checkout, "build it in CI" would produce a different
 *    dashboard from the one you built locally and neither would be a statement
 *    about the tree. Gated by running each generator twice and comparing bytes,
 *    which is ~1.4 s for both.
 * 2. **Neither artifact is tracked.** Re-committing one silently restores every
 *    cost above. Gated by `git ls-files`, and then — for the case where one is
 *    tracked anyway — by regenerating in place and requiring the working tree to
 *    be clean at those two paths, which is the staleness check the old pin was.
 *
 * What the payloads *contain* is asserted by the two tests that used to hold the
 * pins: `packages/scenario/test/unit/ui-recording.test.ts` and
 * `packages/content/test/unit/design-dashboard-payload.test.ts`. Both now run
 * their generator and assert shape and invariants over fresh output.
 *
 * ## Exit codes
 *
 * `scripts/w117-gate-check.sh` is the model, and `CLAUDE.md` states the reason:
 * a checker that folds "the probe is broken" into "the answer is no" is worse
 * than no checker.
 *
 *   0   both artifacts built, deterministic, and untracked.
 *   42  a real finding — a generator is not deterministic, or an artifact is
 *       tracked (and possibly stale).
 *   1   the probe itself broke — a generator crashed, wrote nothing, or wrote
 *       something that is not JSON. Never reported as 42.
 *
 * ## Side effect, on purpose
 *
 * It leaves both artifacts written at their canonical paths. That is what makes
 * `npm run verify` enough to give you a working `npm run ui` locally, and it is
 * what lets the tracked-file case be caught as a dirty tree rather than only as
 * a tracked path.
 */

import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');

const EXIT_OK = 0;
const EXIT_FINDING = 42;
const EXIT_BROKEN_PROBE = 1;

/**
 * The artifacts, each with the generator that writes it and the command a person
 * runs. `artifact` is repository-relative so it can be handed to git unchanged.
 */
const ARTIFACTS = [
  {
    artifact: 'ui/session.json',
    generator: 'scripts/record-session.mjs',
    command: 'npm run ui:record',
    reader: 'the eleven prototypes, through ui/shared/session.js',
  },
  {
    artifact: 'ui/design-dashboard/data.json',
    generator: 'scripts/build-design-dashboard.mjs',
    command: 'npm run ui:dashboard',
    reader: 'ui/design-dashboard/index.html',
  },
];

/** A finding: something is wrong with the repository. Reported, then exit 42. */
const findings = [];
/** The probe could not answer. Reported, then exit 1 — never folded into 42. */
const broken = [];

const scratch = mkdtempSync(path.join(tmpdir(), 'mm-generated-'));

/**
 * Runs one generator to `out`. Returns its bytes, or `null` after recording why
 * the probe could not answer.
 *
 * `stdio` keeps stderr, because both generators write a one-line summary there
 * and a stack trace is the thing you want in the CI log when this returns null.
 */
const generate = (entry, out) => {
  const result = spawnSync(process.execPath, [path.join(ROOT, entry.generator), '--out', out], {
    cwd: ROOT,
    encoding: 'buffer',
    stdio: ['ignore', 'ignore', 'pipe'],
  });
  if (result.error !== undefined) {
    broken.push(`${entry.generator} could not be spawned: ${result.error.message}`);
    return null;
  }
  if (result.status !== 0) {
    const stderr = result.stderr?.toString('utf8').trim() ?? '';
    broken.push(
      `${entry.generator} exited ${String(result.status)}. It is the thing that broke, not the ` +
        `artifact.\n${stderr.replace(/^/gm, '    ')}`,
    );
    return null;
  }
  let bytes;
  try {
    bytes = readFileSync(out);
  } catch (cause) {
    broken.push(`${entry.generator} exited 0 and wrote no file at ${out}: ${cause.message}`);
    return null;
  }
  try {
    JSON.parse(bytes.toString('utf8'));
  } catch (cause) {
    // Distinguished from a diff on purpose: unparseable output means the
    // generator is broken, and reporting that as "the artifact drifted" would
    // send a reader to look at content that does not exist.
    broken.push(`${entry.generator} wrote something that is not JSON: ${cause.message}`);
    return null;
  }
  return bytes;
};

/** Is `relative` tracked by git? `null` when git itself could not be asked. */
const isTracked = (relative) => {
  const result = spawnSync('git', ['ls-files', '--error-unmatch', '--', relative], {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.error !== undefined) return null;
  // 0 = tracked, 1 = not tracked. Anything else is git failing to answer.
  if (result.status === 0) return true;
  if (result.status === 1) return false;
  return null;
};

for (const entry of ARTIFACTS) {
  const first = path.join(scratch, `${path.basename(entry.artifact, '.json')}-1.json`);
  const second = path.join(scratch, `${path.basename(entry.artifact, '.json')}-2.json`);

  const a = generate(entry, first);
  if (a === null) continue;
  const b = generate(entry, second);
  if (b === null) continue;

  if (!a.equals(b)) {
    // The property the whole design rests on. A generator that embeds a
    // timestamp, a path or a machine fact makes "build it in CI" produce a
    // different artifact from the one built locally, and then neither is a
    // statement about the tree.
    findings.push(
      `${entry.generator} is NOT DETERMINISTIC: two runs on this tree differ ` +
        `(${String(a.length)} vs ${String(b.length)} bytes).\n` +
        '    Something machine-specific reached the payload — a clock reading, an absolute path,\n' +
        '    a Map iteration order, a `git` call. Find it and remove it: this artifact is only\n' +
        `    safe to build rather than commit while this holds.\n` +
        `    Compare: ${first}\n         and: ${second}`,
    );
    continue;
  }

  // Written at the canonical path so `npm run ui` works after `npm run verify`,
  // and so a tracked artifact shows up below as a dirty tree.
  const canonical = path.join(ROOT, entry.artifact);
  copyFileSync(first, canonical);

  const tracked = isTracked(entry.artifact);
  if (tracked === null) {
    broken.push(`git could not say whether ${entry.artifact} is tracked.`);
    continue;
  }
  if (tracked) {
    findings.push(
      `${entry.artifact} is TRACKED by git, and it is generated output.\n` +
        `    Run: git rm --cached ${entry.artifact}\n` +
        '    It is a pure function of the repository, so committing it makes every change to its\n' +
        `    inputs also a change to it — see the module note at the top of ${path.relative(ROOT, fileURLToPath(import.meta.url))}.`,
    );
    continue;
  }

  const size = statSync(canonical).size;
  process.stdout.write(
    `  ok  ${entry.artifact.padEnd(30)} deterministic over two runs, untracked, ` +
      `${String(Math.round(size / 1024))} KiB (${entry.command})\n`,
  );
}

// The staleness half of the old pin, kept for the one case it still covers: an
// artifact that got re-committed. Scoped to the two paths so an unrelated stray
// file in someone's worktree cannot report a false finding here — an aggregator
// that answers about the wrong input is the failure mode `CLAUDE.md` names.
if (broken.length === 0) {
  let porcelain;
  try {
    porcelain = execFileSync(
      'git',
      ['status', '--porcelain', '--', ...ARTIFACTS.map((e) => e.artifact)],
      { cwd: ROOT, encoding: 'utf8' },
    ).trim();
  } catch (cause) {
    broken.push(`git status could not be run: ${cause.message}`);
    porcelain = '';
  }
  if (porcelain !== '') {
    findings.push(
      'The working tree is dirty at a generated artifact after regenerating it:\n' +
        `${porcelain.replace(/^/gm, '    ')}\n` +
        '    A tracked copy disagrees with what the generator produces today. Untrack it rather\n' +
        '    than refreshing it.',
    );
  }
}

rmSync(scratch, { recursive: true, force: true });

if (broken.length > 0) {
  process.stderr.write(
    '\nBROKEN PROBE — this check could not answer, which is not the same as "no findings":\n\n' +
      broken.map((line) => `  - ${line}`).join('\n') +
      '\n\nFix the generator, then re-run. Exit 1.\n',
  );
  process.exit(EXIT_BROKEN_PROBE);
}

if (findings.length > 0) {
  process.stderr.write(
    `\nFAIL — ${String(findings.length)} finding(s) in the generated UI artifacts:\n\n` +
      findings.map((line) => `  - ${line}`).join('\n\n') +
      '\n\nExit 42.\n',
  );
  process.exit(EXIT_FINDING);
}

process.stdout.write(
  `\nOK — ${String(ARTIFACTS.length)} generated artifacts built, deterministic, and out of git.\n`,
);
process.exit(EXIT_OK);
